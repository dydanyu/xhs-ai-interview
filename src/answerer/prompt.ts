import type { AnswerInput } from "../types.js";

export function buildAnswerPrompt(input: AnswerInput): string {
  const notesText = input.notes
    .map(
      (n) =>
        `### 笔记 noteId:${n.noteId}\n标题:${n.title}\n来源:${n.url}\n正文:\n${n.content}`
    )
    .join("\n\n");

  return [
    "你是一名资深面试辅导专家。下面是从小红书抓取的若干笔记,其中包含 AI Agent 相关的面试题。",
    "",
    `求职画像:${input.profile}`,
    "",
    "请完成以下工作:",
    "1. 先判别每条笔记是否为【真实面经/面试题】贴。若是广告、课程/训练营推广、引流或无实质题目的贴,则整条【跳过】:不提取、不作答、不写入复习指南。",
    "   广告/引流特征(命中其一即高度可疑):留微信/VX/QQ/联系方式、加群/进群/扫码、训练营/报名/付费课程/限时优惠、押题/包过/内部资料、私我领资料、通篇课程大纲或机构宣传而无具体题目。判别有疑义时,以是否含可作答的真实面试题为准。",
    "2. 对保留的笔记,从正文中提取出独立的面试题(忽略与面试无关的内容)。",
    `3. 与 ${input.guideDir} 目录下已有的复习指南做语义【去重】:已存在的题目不要重复新增,可在原有条目下补充更好的要点。`,
    "4. 为每道新题撰写答案,答案结构包含:核心要点、与前端工程结合的角度、面试加分项。",
    "   在有助于理解的题目上,额外补一段简短代码示例(前端相关用 TypeScript/React,通用概念用伪代码或对应语言;≤15 行,只聚焦关键点)。纯概念/八股题不必强加代码。",
    `5. 按主题把题目+答案写入 ${input.guideDir}/<主题>.md(主题如:Agent 基础概念、LLM 基础、Agent 框架、工程化与部署、前端结合、项目场景题、手写代码题)。文件不存在则创建。`,
    "   「手写代码题」:凡是要求现场手写/实现的编程题(如手写限流器/防抖节流/Promise、实现 ReAct loop、实现 SSE 解析、算法题等)都归到这里,并给出较完整、可运行的代码实现(可超过 15 行),配关键注释与复杂度/边界说明。",
    `6. 全部写完后,重建 ${input.guideDir}/index.md 主题索引。`,
    "",
    "要求:答案准确、简洁、可直接用于复习;每题篇幅适中、避免冗长;全程使用简体中文(专有名词可保留英文),不要混入其它语言;直接修改文件,不要只在对话里回答。",
    "",
    "--- 待处理笔记 ---",
    notesText,
  ].join("\n");
}
